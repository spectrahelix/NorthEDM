// Rebuild utils/numerology/data/pdfFonts.ts: the fonts embedded in the
// server-made PDF (headless Chrome on Vercel ships with almost no fonts).
// All SIL Open Font License, from the @fontsource packages:
//   npm i --no-save @fontsource/noto-sans @fontsource/noto-sans-hebrew @fontsource/noto-sans-symbols
//   node scripts/build-pdf-fonts.mjs <node_modules/@fontsource dir>
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
const dir = process.argv[2] || "node_modules/@fontsource";
const faces = [
  ["NE Hebrew", "noto-sans-hebrew/files/noto-sans-hebrew-hebrew-400-normal.woff2", 400],
  ["NE Hebrew", "noto-sans-hebrew/files/noto-sans-hebrew-hebrew-700-normal.woff2", 700],
  ["NE Sans", "noto-sans/files/noto-sans-latin-400-normal.woff2", 400],
  ["NE Sans", "noto-sans/files/noto-sans-latin-700-normal.woff2", 700],
  ["NE Sans", "noto-sans/files/noto-sans-latin-ext-400-normal.woff2", 400],
  ["NE Sans", "noto-sans/files/noto-sans-latin-ext-700-normal.woff2", 700],
  ["NE Symbols", "noto-sans-symbols/files/noto-sans-symbols-symbols-400-normal.woff2", 400],
];
const css = faces.map(([family, file, weight]) =>
  `@font-face{font-family:"${family}";font-weight:${weight};font-style:normal;src:url(data:font/woff2;base64,${readFileSync(join(dir, file)).toString("base64")}) format("woff2");}`
).join("\n");
writeFileSync("utils/numerology/data/pdfFonts.ts",
  `// Generated by scripts/build-pdf-fonts.mjs — Noto Sans, Noto Sans Hebrew, Noto Sans Symbols (SIL OFL 1.1).\n` +
  `export const PDF_FONT_CSS = ${JSON.stringify(css)};\n`);
console.log(`${faces.length} faces, ${css.length} chars`);
